# Membership operators
# These Operators used to test whether a specific value or item is present in sequence such as string, list tuple or set
# in / not in

list1 = [1, 2, 3, 4, 5]

num = int(input("Enter number: "))

if( num in list1):
    print("number is present in list")
else:
    print("number is not present in list")

